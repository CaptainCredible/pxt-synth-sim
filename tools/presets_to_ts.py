#!/usr/bin/env python3
"""
Turn the preset list in tools/presets.txt into soundpresets.ts (the "preset" dropdown
of the "set up" block).

presets.txt holds presets the way they are shared (and read by the "import preset" block):
a name line, then the MicroSynth Preset struct in braces, e.g.

    FMpluck:
    { OscType::Triangle, OscType::Pulse, 12.000000, ..., false }

Run from the extension folder:   python3 tools/presets_to_ts.py

Each preset becomes an enum member whose blockValues attribute lists the "set up" block's
inputs in the block's own units. The editor (pxt core "presetvalues" field) copies those into
the block when the preset is chosen; nothing extra is compiled into the program.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "presets.txt")
OUT = os.path.join(HERE, "..", "soundpresets.ts")

# MicroSynth Preset struct order (same as paramRemapArray in helpers.ts)
FIELDS = [
    "osc1Shape", "osc2Shape", "osc2Transpose", "osc1Vol", "osc2Vol", "osc1Pw", "osc2Pw",
    "osc1Pwm", "osc2Pwm", "fmAmount", "vcfType", "vcfCutoff", "vcfReso", "vcfEnv", "vcfLfo",
    "vcfKeyFollow", "envA", "envD", "envS", "envR", "lfoShape", "lfoFreq", "vibFreq",
    "vibAmount", "gain", "tune", "noise", "ampGate",
]

# "set up" block input: (struct field, conversion to block units, min, max)
# The conversions are the inverse of synthBlocks.setUpSound in soundsetup.ts.
pct = lambda v: v * 100
NUMBERS = [
    ("osc1Level", "osc1Vol", pct, 0, 100),
    ("tune", "tune", lambda v: v, -12, 12),
    ("osc2Level", "osc2Vol", pct, 0, 100),
    ("osc2Transpose", "osc2Transpose", lambda v: v, -24, 24),
    ("noise", "noise", pct, 0, 100),
    ("volume", "gain", pct, 0, 100),
    ("attack", "envA", lambda v: v * 1000, 0, 2000),
    ("decay", "envD", lambda v: v * 1000, 0, 2000),
    ("sustain", "envS", pct, 0, 100),
    ("release", "envR", lambda v: v * 1000, 0, 3000),
    ("cutoff", "vcfCutoff", pct, 0, 100),
    ("resonance", "vcfReso", pct, 0, 100),
    ("filterEnv", "vcfEnv", pct, 0, 100),
    ("filterKey", "vcfKeyFollow", pct, 0, 100),
    ("filterLfo", "vcfLfo", pct, 0, 100),
    ("lfoFreq", "lfoFreq", lambda v: v, 0, 20),
    ("vibFreq", "vibFreq", lambda v: v, 0, 20),
    ("vibDepth", "vibAmount", lambda v: v * 100, 0, 100),   # semitones -> cents
    ("fm", "fmAmount", pct, 0, 100),
    ("pw1", "osc1Pw", lambda v: (v + 1) * 50, 0, 100),      # -1..1 -> 0..100
    ("pwm1", "osc1Pwm", pct, 0, 100),
    ("pw2", "osc2Pw", lambda v: (v + 1) * 50, 0, 100),
    ("pwm2", "osc2Pwm", pct, 0, 100),
]

SHAPES = {"Saw": "oscShapes.saw", "Pulse": "oscShapes.pulse", "Triangle": "oscShapes.triangle"}
FILTERS = {"LPF": "SynthFilterType.Lowpass", "HPF": "SynthFilterType.Highpass", "BPF": "SynthFilterType.Bandpass"}

# also accepts a missing comma (e.g. "0.152000false")
TOKEN = re.compile(r"OscType::\w+|FilterType::\w+|true|false|-?\d+(?:\.\d+)?")


def parse(text):
    presets = []
    name = None
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("{"):
            if not name:
                sys.exit(f"preset values without a name: {line[:40]}...")
            tokens = TOKEN.findall(line)
            if len(tokens) != len(FIELDS):
                sys.exit(f"{name}: expected {len(FIELDS)} values, found {len(tokens)}")
            presets.append((name, dict(zip(FIELDS, tokens))))
            name = None
        else:
            name = line.rstrip(":").strip()
    return presets


def fmt(v):
    v = round(v, 1)
    return str(int(v)) if v == int(v) else str(v)


def block_values(name, p):
    out = [
        f"osc1Shape={SHAPES[p['osc1Shape'].split('::')[1]]}",
        f"osc2Shape={SHAPES[p['osc2Shape'].split('::')[1]]}",
        f"gateEnv={'gateOrEnv.gate' if p['ampGate'] == 'true' else 'gateOrEnv.ebvelope'}",
        f"filterType={FILTERS[p['vcfType'].split('::')[1]]}",
        f"lfoShape={SHAPES[p['lfoShape'].split('::')[1]]}",
    ]
    for block_name, field, conv, lo, hi in NUMBERS:
        v = conv(float(p[field]))
        if v < lo or v > hi:
            print(f"warning: {name}: {block_name} = {fmt(v)} is outside the block's range {lo}..{hi}", file=sys.stderr)
        out.append(f"{block_name}={fmt(v)}")
    return " ".join(out)


def identifier(name, used):
    ident = "".join(w[:1].upper() + w[1:] for w in re.findall(r"[A-Za-z0-9]+", name)) or "Preset"
    if ident[0].isdigit():
        ident = "P" + ident
    base, n = ident, 2
    while ident in used:
        ident, n = f"{base}{n}", n + 1
    used.add(ident)
    return ident


def main():
    with open(SRC, encoding="utf-8") as f:
        presets = parse(f.read())

    used = {"Custom"}
    lines = [
        "// Generated by tools/presets_to_ts.py from tools/presets.txt - edit those and re-run.",
        "",
        "/**",
        " * Ready-made sounds for the \"set up\" block. Choosing one in the editor copies its",
        " * values into the block's inputs (pxt core \"presetvalues\" field), so only the values",
        " * on the block end up in the program.",
        " */",
        "enum SynthSoundPreset {",
        "    //% block=\"custom\"",
        "    Custom = 0,",
    ]
    for i, (name, p) in enumerate(presets):
        lines.append(f"    //% block=\"{name}\"")
        lines.append(f"    //% blockValues=\"{block_values(name, p)}\"")
        lines.append(f"    {identifier(name, used)} = {i + 1},")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(presets)} presets to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
